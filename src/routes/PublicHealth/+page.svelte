<h2>@DVRPC</h2>
<h3><strong>#1 Behind the Data:</strong> Uncovering the Impact of College Population and Transit Access on Philadelphia's Pedestrian Activity</h3>
<p>
The Delaware Valley Regional Planning Commission (DVRPC)’s Southeastern Pennsylvania Cyclical Pedestrian Counting Program tracks pedestrian volumes at 170 locations across Bucks, Chester, Delaware, Montgomery, and Philadelphia counties. The project team employed a stratified random sampling methodology, using strata defined by census tract characteristics and transit ridership to select count locations. I conducted an analysis aimed at assessing whether the current stratification approach is statistically significant in capturing the variations in pedestrian activity levels. By examining the effectiveness of using census tract characteristics and transit ridership data, the analysis seeks to ensure that the chosen strata effectively reflect the diversity in pedestrian activity.
